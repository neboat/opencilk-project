#ifndef KITSUNE_CORE_TARGET_UTILS_H
#define KITSUNE_CORE_TARGET_UTILS_H

#include "kitsune/Core/Tapir.h"
#include "llvm/Support/CodeGen.h"

namespace llvm {

class KitsuneTTOptions;
class MCTargetOptions;
class TargetMachine;
class TargetOptions;
class raw_ostream;

/// Create a target machine to optimize/compile device code generated by the
/// given tapir target. Currently, this is only relevant for the GPU tapir
/// targets. The machine is configured with the options in the
/// KitsuneTTOptions object that is provided. The optimization level to use in
/// the target machine is derived from the optimization level set in the
/// \ref KitsuneTTOptions.
TargetMachine *createTargetMachine(TTID tt, const KitsuneTTOptions &tto);

/// Create a target machine to optimize/compile device code generated by the
/// given tapir target. Currently ,this is only relevant for the GPU tapir
/// targets. The machine is configured with the options in the
/// KitsuneTTOptions object that is provided. The exception is the
/// optimization level which is provided explicitly.
TargetMachine *createTargetMachine(TTID tt, const KitsuneTTOptions &tto,
                                   CodeGenOptLevel cgOptLevel);

/// Create a "default" target machine. This is typically the target machine for
/// the default triple for the current Kitsune build. This will typically be
/// the host. The machine will *NOT* be specialized for the specific host CPU.
TargetMachine *createHostTargetMachine(const KitsuneTTOptions &tto);

/// Dump the contents of the TargetOptions object to the given output stream.
void dump(const TargetOptions &, raw_ostream &);

/// Dump the contents of the MCTargetOptions object to the given output stream.
void dump(const MCTargetOptions &, raw_ostream &);

} // namespace llvm

#endif // KITSUNE_CORE_TARGET_UTILS_H
